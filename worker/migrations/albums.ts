// SQL for migration 0015_albums.sql: the one definition shared by the tests (via index.ts) and the .sql
// file, which `npm run gen:albums-migration` generates. test/albums-migration.test.ts fails if they drift.
import { COMBINED_SCORE_SQL } from '../src/db/rating';

const COLUMNS = 'name, photo_count, latest_date, newest_indexed, avg_score, cover_photo_id, content_hash';

/**
 * Rebuilds the `albums` rows of the albums matched by `where` (a condition on photos.album) from the
 * photos table, using the covering index idx_photos_album_cover. Cover: the pick in album_covers while
 * that photo is still in the album, else the newest dated photo, else the newest indexed.
 * owner_email and shared_with (added by 0016) are owner-edited: they are deliberately absent from COLUMNS and
 * from the DO UPDATE SET list below, so a refresh never touches them.
 */
function upsertAlbums(where: string): string {
  return `INSERT INTO albums (${COLUMNS})
SELECT g.album, g.cnt, g.newest_date, g.newest_indexed, g.avg_score, g.cover_id,
       (SELECT content_hash FROM photos WHERE id = g.cover_id)
FROM (
  SELECT album, COUNT(*) AS cnt, MAX(date_time) AS newest_date, MAX(last_indexed) AS newest_indexed,
         AVG(${COMBINED_SCORE_SQL}) AS avg_score,
         COALESCE(
           (SELECT c.photo_id FROM album_covers c
             WHERE c.album = photos.album AND EXISTS (SELECT 1 FROM photos p WHERE p.id = c.photo_id AND p.album = c.album)),
           (SELECT id FROM photos p WHERE p.album = photos.album AND p.date_time IS NOT NULL
             ORDER BY p.date_time DESC, p.last_indexed DESC LIMIT 1),
           (SELECT id FROM photos p WHERE p.album = photos.album AND p.date_time IS NULL
             ORDER BY p.last_indexed DESC LIMIT 1)
         ) AS cover_id
  FROM photos WHERE ${where} GROUP BY album
) g WHERE true
ON CONFLICT(name) DO UPDATE SET
  photo_count = excluded.photo_count, latest_date = excluded.latest_date, newest_indexed = excluded.newest_indexed,
  avg_score = excluded.avg_score, cover_photo_id = excluded.cover_photo_id, content_hash = excluded.content_hash;`;
}

/** Rebuilds one album's row, or removes it when the album has no photos left. */
function refreshAlbum(albumExpr: string): string {
  return `${upsertAlbums(`album = ${albumExpr}`)}
  DELETE FROM albums WHERE name = ${albumExpr} AND NOT EXISTS (SELECT 1 FROM photos WHERE album = ${albumExpr});`;
}

const trigger = (name: string, event: string, when: string, body: string) =>
  `CREATE TRIGGER IF NOT EXISTS ${name} ${event}\nWHEN ${when} BEGIN\n  ${body}\nEND;`;

// Columns that feed an album's row; a photo UPDATE touching only other columns (path, faces_scanned_model)
// must not recompute anything.
const FEEDS = ['album', 'date_time', 'last_indexed', 'user_rating', 'aesthetic_score'];
const FEEDS_CHANGED = FEEDS.map((c) => `old.${c} IS NOT new.${c}`).join(' OR ');

export const ALBUMS_SCHEMA_STATEMENTS = [
  'CREATE INDEX IF NOT EXISTS idx_photos_last_indexed ON photos (last_indexed DESC, id);',
  `CREATE TABLE IF NOT EXISTS albums (
  name TEXT PRIMARY KEY,
  photo_count INTEGER NOT NULL,
  latest_date TEXT,
  newest_indexed TEXT NOT NULL,
  avg_score REAL,
  cover_photo_id TEXT NOT NULL,
  content_hash TEXT
) WITHOUT ROWID;`,
  `CREATE TABLE IF NOT EXISTS counters (
  name TEXT PRIMARY KEY,
  n INTEGER NOT NULL
) WITHOUT ROWID;`,
];

export const ALBUMS_TRIGGER_STATEMENTS = [
  trigger('counts_ai', 'AFTER INSERT ON photos', 'true', "UPDATE counters SET n = n + 1 WHERE name = 'photos';"),
  trigger('counts_ad', 'AFTER DELETE ON photos', 'true', "UPDATE counters SET n = n - 1 WHERE name = 'photos';"),
  trigger('albums_photo_ai', 'AFTER INSERT ON photos', 'new.album IS NOT NULL', refreshAlbum('new.album')),
  trigger('albums_photo_ad', 'AFTER DELETE ON photos', 'old.album IS NOT NULL', refreshAlbum('old.album')),
  trigger(
    'albums_photo_au_old',
    `AFTER UPDATE OF ${FEEDS.join(', ')} ON photos`,
    'old.album IS NOT NULL AND old.album IS NOT new.album',
    refreshAlbum('old.album')
  ),
  trigger(
    'albums_photo_au_new',
    `AFTER UPDATE OF ${FEEDS.join(', ')} ON photos`,
    `new.album IS NOT NULL AND (${FEEDS_CHANGED})`,
    refreshAlbum('new.album')
  ),
  trigger('albums_cover_ai', 'AFTER INSERT ON album_covers', 'true', refreshAlbum('new.album')),
  trigger('albums_cover_au', 'AFTER UPDATE ON album_covers', 'true', refreshAlbum('new.album')),
  trigger('albums_cover_ad', 'AFTER DELETE ON album_covers', 'true', refreshAlbum('old.album')),
];

/** One-off backfill for existing data; the test database starts empty, so index.ts leaves it out. */
export const ALBUMS_BACKFILL_STATEMENTS = [
  'DELETE FROM albums;',
  upsertAlbums('album IS NOT NULL'),
  "INSERT OR REPLACE INTO counters (name, n) SELECT 'photos', COUNT(*) FROM photos;",
];

export function albumsMigrationSql(): string {
  const all = [...ALBUMS_SCHEMA_STATEMENTS, ...ALBUMS_BACKFILL_STATEMENTS, ...ALBUMS_TRIGGER_STATEMENTS];
  return `-- GENERATED by \`npm run gen:albums-migration\` from migrations/albums.ts. Edit that file, not this one.
-- Additive only.
--
-- albums: one row per non-null album with everything the albums page shows (count, cover, newest date,
-- average score), kept by triggers on photos and album_covers so every write path stays consistent and the
-- page reads one small table instead of aggregating photos. counters: the total photo count for the
-- unfiltered list. idx_photos_last_indexed: the unfiltered newest-first list had no index.
${all.join('\n\n')}
`;
}
